def load_initial_questions():
    """
    Idempotently seeds all 150 questions across 3 age groups into SQLite.
    Identity key: (assessment_type, age_group, order).
    Running multiple times updates existing records without creating duplicates.
    """
    created_count = 0
    updated_count = 0

    for q_data in ALL_SEED_QUESTIONS:
        q, created = Question.objects.update_or_create(
            assessment_type=q_data['assessment_type'],
            age_group=q_data['age_group'],
            order=q_data['order'],
            defaults={
                'category': q_data['category'],
                'difficulty': q_data.get('difficulty', Question.Difficulty.MEDIUM),
                'question_text': q_data['question_text'],
                'option_a': q_data['option_a'],
                'option_b': q_data['option_b'],
                'option_c': q_data['option_c'],
                'option_d': q_data['option_d'],
                'correct_option': q_data.get('correct_option'),
                'option_a_category': q_data.get('option_a_category', ''),
                'option_b_category': q_data.get('option_b_category', ''),
                'option_c_category': q_data.get('option_c_category', ''),
                'option_d_category': q_data.get('option_d_category', ''),
                'is_active': True,
            }
        )
        if created:
            created_count += 1
        else:
            updated_count += 1

    return created_count, updated_count
